"""A deterministic, in-process stand-in for the PayPal Disputes API.

Why this exists
---------------
The hackathon submission requires a functional demonstration: judges must be
able to run or interact with a working build. CaseGraph's real value is only
visible after a PayPal write, which normally needs sandbox credentials that a
reviewer does not have. This module supplies a *clearly labelled* simulated
transport so the complete journey — authoritative sync, evidence intake, AI
reasoning, deterministic safety, human approval, execution, reconciliation —
runs locally with no credentials and no network access.

Safety properties
-----------------
* It is unreachable in production: ``backend.main`` refuses to start and
  ``SecurityConfig.validate()`` reports an error when the simulated transport is
  selected with ``CASEGRAPH_ENV=production``.
* Every response is stamped ``"simulated": true`` and each mutating call bumps a
  ``simulation_revision`` so persisted PayPal responses can never be mistaken for
  authoritative provider state.
* It models the same HATEOAS-link contract the real API uses, so the real
  action-availability validation still runs. Nothing is bypassed.
"""

from __future__ import annotations

import json
import threading
from pathlib import Path
from typing import Any

from backend.paypal.errors import PayPalAPIError, PayPalTransportError
from backend.paypal.simulation_data import demo_state

_LOCK = threading.RLock()

#: Operations that mutate simulated PayPal state. Transport faults are injected
#: only into these, so read paths keep working while a write outcome is unknown.
MUTATING_OPERATIONS = {
    "send_message",
    "make_offer",
    "accept_claim",
    "provide_dispute_evidence",
    "appeal_dispute",
    "escalate",
    "supporting_info",
    "acknowledge_return",
}

_LINKS_BY_STATUS: dict[str, tuple[str, ...]] = {
    "WAITING_FOR_SELLER_RESPONSE": (
        "send-message",
        "provide-evidence",
        "make-offer",
        "accept-claim",
        "escalate",
        "provide-supporting-info",
    ),
    "UNDER_REVIEW": ("send-message", "provide-supporting-info"),
    "RESOLVED_BUYER_FAVOUR": (),
    "RESOLVED_SELLER_FAVOUR": (),
}


def _links(rels: tuple[str, ...]) -> list[dict[str, str]]:
    return [{"rel": rel, "method": "POST", "href": f"https://simulated.invalid/{rel}"} for rel in rels]


class SimulatedPayPal:
    """Stateful simulator persisted to a single JSON file.

    A file (rather than process memory) keeps the API and the durable worker
    consistent when they run as separate processes in a local demo.
    """

    def __init__(self, state_path: Path, *, fault: str = "none") -> None:
        self.state_path = Path(state_path)
        self.fault = (fault or "none").strip().lower()

    # ------------------------------------------------------------------ state
    def _load(self) -> dict[str, Any]:
        if not self.state_path.exists():
            state = demo_state()
            self._save(state)
            return state
        try:
            return json.loads(self.state_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            # A corrupt demo state must not silently become a half-valid case
            # store; rebuild the deterministic fixtures instead.
            state = demo_state()
            self._save(state)
            return state

    def _save(self, state: dict[str, Any]) -> None:
        self.state_path.parent.mkdir(parents=True, exist_ok=True)
        tmp = self.state_path.with_suffix(".tmp")
        tmp.write_text(json.dumps(state, indent=2, sort_keys=True), encoding="utf-8")
        tmp.replace(self.state_path)

    def reset(self) -> None:
        with _LOCK:
            self._save(demo_state())

    # ------------------------------------------------------------- rendering
    def _render(self, state: dict[str, Any], dispute_id: str) -> dict[str, Any]:
        dispute = dict(state["disputes"][dispute_id])
        status = str(dispute.get("status") or "")
        dispute["links"] = _links(_LINKS_BY_STATUS.get(status, ()))
        dispute["simulated"] = True
        dispute["simulation_revision"] = int(state["revision"][dispute_id])
        dispute["simulation_note"] = (
            "SIMULATED PayPal sandbox payload generated by CaseGraph. "
            "Not authoritative PayPal state; never use for a real dispute."
        )
        messages = state["messages"].get(dispute_id) or []
        if messages:
            dispute["messages"] = messages
        return dispute

    def _require(self, state: dict[str, Any], dispute_id: str) -> None:
        if dispute_id not in state["disputes"]:
            raise PayPalAPIError(
                "get_dispute failed: simulated dispute not found",
                404,
                {"name": "INVALID_RESOURCE_ID", "dispute_id": dispute_id},
            )

    def _bump(self, state: dict[str, Any], dispute_id: str) -> None:
        state["revision"][dispute_id] = int(state["revision"].get(dispute_id, 0)) + 1

    def _apply_fault(self, operation: str) -> None:
        if self.fault == "timeout" and operation in MUTATING_OPERATIONS:
            raise PayPalTransportError(
                f"{operation}: simulated network timeout (CASEGRAPH_SIMULATED_FAULT=timeout)"
            )
        if self.fault == "server_error" and operation in MUTATING_OPERATIONS:
            raise PayPalAPIError(
                f"{operation} failed: simulated 503 (CASEGRAPH_SIMULATED_FAULT=server_error)",
                503,
                {"name": "SERVICE_UNAVAILABLE"},
            )

    # ------------------------------------------------------------------ read
    def get_dispute(self, dispute_id: str) -> dict[str, Any]:
        with _LOCK:
            state = self._load()
            self._require(state, dispute_id)
            return self._render(state, dispute_id)

    def list_disputes(self) -> dict[str, Any]:
        with _LOCK:
            state = self._load()
            items = [self._render(state, key) for key in sorted(state["disputes"])]
            return {"items": items, "total_items": len(items), "simulated": True}

    # ---------------------------------------------------------------- writes
    def write(self, operation: str, dispute_id: str, body: dict[str, Any] | None = None) -> dict[str, Any]:
        self._apply_fault(operation)
        with _LOCK:
            state = self._load()
            self._require(state, dispute_id)
            dispute = state["disputes"][dispute_id]
            body = body or {}

            if operation == "send_message":
                state["messages"].setdefault(dispute_id, []).append(
                    {"posted_by": "SELLER", "message": str(body.get("message") or "")}
                )
            elif operation == "provide_dispute_evidence":
                dispute["status"] = "UNDER_REVIEW"
                dispute["evidence_supplied"] = True
            elif operation == "appeal_dispute":
                dispute["status"] = "UNDER_REVIEW"
                dispute["appealed"] = True
            elif operation == "escalate":
                dispute["status"] = "UNDER_REVIEW"
                dispute["dispute_life_cycle_stage"] = "CHARGEBACK"
            elif operation == "supporting_info":
                dispute["status"] = "UNDER_REVIEW"
            elif operation == "make_offer":
                dispute["status"] = "UNDER_REVIEW"
                dispute["last_offer"] = body
            elif operation == "accept_claim":
                dispute["status"] = "RESOLVED_BUYER_FAVOUR"
            elif operation == "acknowledge_return":
                dispute["return_acknowledged"] = True
            else:  # pragma: no cover - guarded by the caller's operation map
                raise PayPalAPIError(f"unsupported simulated operation {operation!r}", 400, {})

            self._bump(state, dispute_id)
            self._save(state)
            return {
                "simulated": True,
                "operation": operation,
                "dispute_id": dispute_id,
                "status": dispute.get("status"),
            }

    def verify_webhook_signature(self) -> dict[str, Any]:
        return {"verification_status": "SUCCESS", "simulated": True}


def build_simulator(state_path: Path | str, *, fault: str = "none") -> SimulatedPayPal:
    return SimulatedPayPal(Path(state_path), fault=fault)
